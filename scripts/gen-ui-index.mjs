// Regenerates packages/ui/src/index.ts (core) and packages/ui/src/three/index.ts (3D)
// from the files on disk. Safe to run any time; never hand-edit those two files.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "packages/ui/src");

const list = (dir, exts) =>
  fs
    .readdirSync(path.join(src, dir))
    .filter((f) => exts.some((e) => f.endsWith(e)) && f !== "index.ts")
    .sort()
    .map((f) => `./${dir}/${f.replace(/\.(tsx|ts)$/, "")}`);

const core = [...list("lib", [".ts"]), ...list("components", [".tsx", ".ts"])];
fs.writeFileSync(
  path.join(src, "index.ts"),
  `// AUTO-GENERATED by scripts/gen-ui-index.mjs: do not edit.\n// pixel3d-ui core components. 3D lives in "@pixel3d/ui/three".\n${core
    .map((p) => `export * from "${p}";`)
    .join("\n")}\n`
);

const three = fs
  .readdirSync(path.join(src, "three"))
  .filter((f) => /\.(tsx|ts)$/.test(f) && f !== "index.ts")
  .sort()
  .map((f) => `export * from "./${f.replace(/\.(tsx|ts)$/, "")}";`);
fs.writeFileSync(path.join(src, "three/index.ts"), `// AUTO-GENERATED by scripts/gen-ui-index.mjs: do not edit.\n${three.join("\n")}\n`);

console.log(`[gen-ui-index] ${core.length} core modules, ${three.length} three modules`);
