// Generates content/components/_index.ts from content/components/*.tsx.
// Each doc file must contain literal `slug: "…"`, `name: "…"` and `category: "…"` lines.
// Run automatically before dev/build (see package.json). Never edit _index.ts by hand.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, "../content/components");
const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".tsx") && !f.startsWith("_"))
  .sort();

const meta = [];
for (const f of files) {
  const src = fs.readFileSync(path.join(dir, f), "utf8");
  const get = (k) => src.match(new RegExp(`\\b${k}:\\s*"([^"]+)"`))?.[1];
  const slug = get("slug");
  const name = get("name");
  const category = get("category");
  if (!slug || !name || !category) {
    console.warn(`[gen-index] skipped ${f}: needs slug/name/category literals`);
    continue;
  }
  if (slug !== f.replace(/\.tsx$/, "")) console.warn(`[gen-index] ${f}: slug "${slug}" should match file name`);
  meta.push({ slug, name, category, file: f.replace(/\.tsx$/, "") });
}

const out = `// AUTO-GENERATED by scripts/gen-index.mjs — do not edit.
import type { ComponentDoc, DocMeta } from "@/lib/types";

export const meta: DocMeta[] = ${JSON.stringify(meta.map(({ file, ...m }) => m), null, 2)};

export const loaders: Record<string, () => Promise<{ doc: ComponentDoc }>> = {
${meta.map((m) => `  ${JSON.stringify(m.slug)}: () => import("./${m.file}"),`).join("\n")}
};
`;
fs.writeFileSync(path.join(dir, "_index.ts"), out);
console.log(`[gen-index] ${meta.length} component docs indexed`);
